"""Render the Kedro DAG as Mermaid, which GitHub draws inline.

``kedro viz`` is the interactive view and the one the exercise asks for, but it
needs a running server and a browser. This writes the same graph as text, so the
structure is reviewable in the repository itself — in a diff, on the web, in the
submitted zip — and a test keeps it honest when the pipelines change.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

from diabetes.pipelines.data_engineering import pipeline as data_engineering
from diabetes.pipelines.inference import pipeline as inference
from diabetes.pipelines.modelling import pipeline as modelling

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "pipelines.md"

PIPELINES = {
    "data_engineering": data_engineering.create_pipeline(),
    "modelling": modelling.create_pipeline(),
    "inference": inference.create_pipeline(),
}

HEADINGS = {
    "data_engineering": (
        "Data engineering",
        "Raw CSV to master table. Every `fit_*` output is persisted, because inference must apply these, never refit them.",
    ),
    "modelling": (
        "Modelling",
        "Two candidates on the same feature contract; the better held-out `roc_auc` is promoted.",
    ),
    "inference": (
        "Inference",
        "Loads the promoted model and the four fitted transformers, and applies the identical transform chain.",
    ),
}


def _ident(name: str) -> str:
    return re.sub(r"\W", "_", name)


def _catalog() -> dict:
    return yaml.safe_load((ROOT / "conf" / "base" / "catalog.yml").read_text())


def _layer(catalog: dict, name: str) -> str | None:
    entry = catalog.get(name)
    if not entry:
        return None
    return (entry.get("metadata") or {}).get("kedro-viz", {}).get("layer")


def _diagram(pipeline, catalog: dict) -> str:
    lines = ["```mermaid", "flowchart LR"]
    seen: set[str] = set()

    for node in pipeline.nodes:
        lines.append(f"  n_{_ident(node.name)}([{node.name}])")

    for node in pipeline.nodes:
        for dataset in (*node.inputs, *node.outputs):
            if dataset.startswith("params:") or dataset in seen:
                continue
            seen.add(dataset)
            layer = _layer(catalog, dataset)
            label = f"{dataset}<br/>({layer})" if layer else dataset
            shape = f'[("{label}")]' if dataset in catalog else f'["{label}"]'
            lines.append(f"  d_{_ident(dataset)}{shape}")

    for node in pipeline.nodes:
        for source in node.inputs:
            if source.startswith("params:"):
                continue
            lines.append(f"  d_{_ident(source)} --> n_{_ident(node.name)}")
        for target in node.outputs:
            lines.append(f"  n_{_ident(node.name)} --> d_{_ident(target)}")

    lines.append("```")
    return "\n".join(lines)


def render() -> str:
    catalog = _catalog()
    out = [
        "# Pipeline diagrams",
        "",
        "Generated by `make diagram` (`scripts/export_pipeline_diagram.py`) and",
        "checked by `test_the_committed_diagram_is_current`, so these cannot drift",
        "from the code. Rounded nodes are functions; cylinders are catalog datasets,",
        "labelled with their `kedro-viz` layer where they declare one.",
        "",
        "For the interactive version, with layer bands and dataset previews:",
        "",
        "```bash",
        "uv run kedro viz",
        "```",
        "",
    ]
    for name, pipeline in PIPELINES.items():
        heading, blurb = HEADINGS[name]
        out += [
            f"## {heading}",
            "",
            f"`{name}` — {len(pipeline.nodes)} nodes. {blurb}",
            "",
            _diagram(pipeline, catalog),
            "",
        ]
    return "\n".join(out)


if __name__ == "__main__":
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(render())
    print(f"wrote {TARGET.relative_to(ROOT)}")
